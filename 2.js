// Создаем функцию getChange(num), которая принимает число num и возвращает массив монет, которые нужно выдать в качестве сдачи
function getChange(num) {
    // Создаем массив coins, который содержит номиналы монет в порядке убывания
    let coins = [10, 5, 2, 1];
    // Создаем пустой массив result, который будет содержать монеты, которые нужно выдать в качестве сдачи
    let result = [];

    // Проходим по каждому номиналу монеты в массиве coins
    for(let i = 0; i < coins.length; i++) {
        // Если текущий номинал монеты меньше или равен num
        if(num >= coins[i]) {
            // Вычитаем номинал монеты из num
            num -= coins[i];
            // Добавляем номинал монеты в массив result
            result.push(coins[i]);
            // Рекурсивно вызываем функцию getChange() с новым значением num
            result = result.concat(getChange(num));
            // Возвращаем массив result, который содержит монеты, которые нужно выдать в качестве сдачи
            return result;
        }
    }

    // Если мы прошли по всем номиналам монет и не нашли подходящего, возвращаем пустой массив
    return [];
}

// Создаем интерфейс readline, чтобы получить ввод пользователя в консоли
const readline = require('readline').createInterface({
    input: process.stdin,
    output: process.stdout
});

// Запрашиваем у пользователя сумму, которую нужно разменять
readline.question('Введите сумму, которую нужно разменять: ', (num) => {
    // Вызываем функцию getChange(num) и выводим результат в консоль
    console.log(getChange(num));
    // Закрываем интерфейс readline
    readline.close();
});





